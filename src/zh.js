/* 间奏诗卡：器乐段没有唱词，用竖排诗卡补足画面（参考片诗卡式）
 * `x` / `y` 可选：不指定则居中（H*.52）。太空镜头里星球占中间，
 * 卡片要挪到侧边，否则压在星球上。 */
var SUB_CARDS = [
  { t0: 116.500, t1: 127.500, text: '团子大家族' },
  { t0: 199.000, t1: 209.000, text: '宇宙巡游', x: 0.135, y: 0.46 }
];
function cardAt(t) {
  for (var i = 0; i < SUB_CARDS.length; i++) {
    var c = SUB_CARDS[i];
    if (t >= c.t0 && t < c.t1) {
      var a = Math.min(1, (t - c.t0) / .6, (c.t1 - t) / .6);
      return { text: c.text, alpha: clamp(a, 0, 1), x: c.x, y: c.y };
    }
  }
  return null;
}
