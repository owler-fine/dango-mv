"""plan_tail_cuts.py — 给出尾奏两种方案的具体切点与受影响镜长。

方案 A（挪切点对齐歌词）：把 3 个尾奏镜的边界改成 4 条歌词的起唱时刻。
方案 B（画面不动，仅构图微调）：不改边界，只列每镜需要做的构图动作。
"""
import io
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

BPM = 99.0
BEAT = 60 / BPM
DUR = 273.031825

# 尾奏 7 条歌词起唱（来自 lyrics.js）
L = [237.55, 242.43, 247.21, 251.91, 256.82, 261.64, 266.38]
Z = [237.55, 240.00, 247.21, 256.82, 266.38]   # 现有镜头边界

print("拍长 BEAT = %.4f s\n" % BEAT)


def to_beat(t):
    return round(t / BEAT)


print("=== 现状切点相对拍点相位 ===")
for t in Z + L:
    n = t / BEAT
    ph = n - round(n)
    print("t=%7.2f  拍号%8.3f  相位 %+.3f (%.0f ms)" % (t, n, ph, ph * BEAT * 1000))

print("\n=== 方案 A：切点对齐歌词起唱 ===")
newcuts = [237.55, 242.43, 247.21, 251.91, 256.82, 261.64, 266.38]
names = ["フェード", "だんご×4(尾)", "大家族(尾)", "だんご×4(尾a)",
         "だんご×4(尾2)", "大家族(尾b)", "だんご×4(尾c)"]
prev = 240.00
print("镜名                起       止      时长   相位数(相对拍)")
for i, c in enumerate(newcuts):
    end = newcuts[i + 1] if i + 1 < len(newcuts) else DUR
    if c < 240:
        continue
    n = c / BEAT
    print("%-16s %7.2f %8.2f %7.2f  %8.3f" % (names[i], c, end, end - c, n))

print("\n=== 方案 B：边界不动，各镜需做的构图动作 ===")
plan = [
    ("#76 だんご×4 (尾)  [240.00..247.21]",
     "含 242.43「だんご×4」→ 语义自洽；另有 240.00..242.43 (2.43s) 无词空镜，"
     "把 6 只团子做成齐步弹跳、收在左 2/3，右侧留白给空拍。"),
    ("#77 大家族 (尾)     [247.21..256.82]",
     "含 247.21「だんご大家族」+251.91「だんご×4」两句，是全片唯一真·跨语义镜。"
     "做法：把 9 只排成「V 字/扇形」并把中心 1 只放大 1.35x 做主角，"
     "让 247.21 的『大家族』落在主角；251.91 起用一套 0.61s 拍点整体上下弹跳，"
     "把『×4』的四拍编码进动作，用节奏把两句切成视觉上的两拍。"),
    ("#78 だんご×4 (尾2)  [256.82..266.38]",
     "含 256.82「だんご だんご大家族」+261.64「だんご×4」。"
     "做法：256.82 起 6 只小团子向中心聚拢合成 1 只大团子（蒙太奇），"
     "261.64 起大团子原地四次蹲跳——画面元素由『聚』转『跳』，与词的『×4』同步。"),
]
for a, b in plan:
    print("\n" + a)
    print("   " + b)

print("\n=== 方案 B 的 4 条歌词逐一对照 ===")
rows = [
    (242.43, "#76 だんご×4 (尾)", "だんご だんご だんご だんご", "6 只团子弹跳，右侧留白"),
    (251.91, "#77 大家族 (尾)", "だんご だんご だんご だんご", "9 只扇形 + 中心 1 只放大"),
    (256.82, "#78 だんご×4 (尾2)", "だんご だんご大家族", "小团子聚合成 1 只大团子"),
    (261.64, "#78 だんご×4 (尾2)", "だんご だんご だんご だんご", "大团子四次蹲跳"),
]
for t, shot, lyric, act in rows:
    print("%7.2f  %-22s %-24s → %s" % (t, shot, lyric, act))
